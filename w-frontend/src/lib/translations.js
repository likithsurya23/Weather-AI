/**
 * Safely fetches translated text for the current language.
 * Falls back to English, and then to fallbackText if key is not found.
 */
export function getTranslation(language = 'English', key = '', fallbackText = '') {
  if (!key) return fallbackText;

  // 1. Direct check in active language
  if (translations[language] && translations[language][key] !== undefined) {
    return translations[language][key];
  }

  // 2. Fallback to English
  if (translations['English'] && translations['English'][key] !== undefined) {
    return translations['English'][key];
  }

  // 3. Fallback to provided default text or key
  return fallbackText || key;
}
